    to_tsvector('pg_catalog.simple',translate(translate(title || ' ' || body || ' ' || summary || ' ' || COALESCE(tags::text,''),'Iİ','ıi'),'ÇçĞğÖöŞşÜüıÂâÎîÛû','CcGgOoSsUuiAaIiUu'))
$$;
CREATE OR REPLACE FUNCTION cor_resource_text(data jsonb)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT COALESCE((SELECT string_agg(COALESCE(item->>'name','') || ' ' || COALESCE(item->>'quantity','') || ' ' || COALESCE(item->>'category','') || ' ' || COALESCE(item->>'note',''),' ' ORDER BY n)
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(data#>'{shopping,items}')='array' THEN data#>'{shopping,items}' ELSE '[]'::jsonb END) WITH ORDINALITY AS entries(item,n)), '') || ' ' ||
    COALESCE((SELECT string_agg(COALESCE(item->>'title','') || ' ' || COALESCE(item->>'location',''),' ' ORDER BY n)
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(data#>'{program,entries}')='array' THEN data#>'{program,entries}' ELSE '[]'::jsonb END) WITH ORDINALITY AS entries(item,n)), '')
$$;
